# Figure 1 – Pipeline Architecture Diagram
# ═══════════════════════════════════════════════════════════════════════════

def fig1_pipeline_diagram(out_dir: Path):
    """Programmatic pipeline flow-chart."""
    fig, ax = plt.subplots(figsize=(16, 5))
    ax.set_xlim(0, 16)
    ax.set_ylim(0, 5)
    ax.axis("off")
    fig.patch.set_facecolor(BG_COLOR)

    # Pipeline stages
    stages = [
        ("Video\nInput",             "#3498db", "V", 1.0),
        ("Frame\nExtraction",        "#2980b9", "F",  3.2),
        ("YOLOv8\nDetection",        "#8e44ad", "D", 5.4),
        ("BoT-SORT\nTracking",       "#2c3e50", "T", 7.6),
        ("WHO 2021\nKinematics",     "#27ae60", "K", 9.8),
        ("Motility\nClassification", "#e67e22", "C",  12.0),
        ("Clinical\nReport + LLM",   "#c0392b", "R", 14.2),
    ]

    box_w, box_h = 1.8, 2.2
    y_center = 2.5

    for label, color, icon, x_center in stages:
        # Draw rounded box
        box = FancyBboxPatch(
            (x_center - box_w / 2, y_center - box_h / 2), box_w, box_h,
            boxstyle="round,pad=0.15", facecolor=color, edgecolor="white",
            linewidth=2, alpha=0.92,
        )
        ax.add_patch(box)

        # Icon letter in circle
        ax.text(x_center, y_center + 0.35, icon, ha="center", va="center",
                fontsize=20, fontweight="bold", color="white",
                family="monospace")

        # Label
        txt = ax.text(x_center, y_center - 0.4, label, ha="center",
                      va="center", fontsize=10, fontweight="bold",
                      color="white", linespacing=1.3)
        txt.set_path_effects([
            path_effects.withStroke(linewidth=2, foreground=color)])

    # Arrows between boxes
    for i in range(len(stages) - 1):
        x1 = stages[i][3] + box_w / 2 + 0.05
        x2 = stages[i + 1][3] - box_w / 2 - 0.05
        ax.annotate("", xy=(x2, y_center), xytext=(x1, y_center),
                    arrowprops=dict(arrowstyle="-|>", color="#555555",
                                    lw=2.5, mutation_scale=18))

    # Title
    ax.text(8, 4.7, "SpermNet — Automated Sperm Motility Analysis Pipeline",
            ha="center", va="center", fontsize=17, fontweight="bold",
            color="#2c3e50")

    # Bottom annotations
    annotations = [
        (1.0,  "50 fps, 640×480"),
        (3.2,  "JPEG frames"),
        (5.4,  "3 classes"),
        (7.6,  "Multi-object"),
        (9.8,  "8 parameters"),
        (12.0, "P / NP / Im"),
        (14.2, "GPT-4o / Claude"),
    ]
    for x, text in annotations:
        ax.text(x, y_center - box_h / 2 - 0.35, text, ha="center",
                va="top", fontsize=8, color="#666666", style="italic")

    _save(fig, out_dir / "fig1_pipeline_architecture.png")


