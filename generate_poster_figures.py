# Figure 5 – Temporal Dynamics
# ═══════════════════════════════════════════════════════════════════════════

def fig5_temporal_dynamics(out_dir: Path):
    """Enhanced stacked area chart of motility evolution over time."""
    agg_csv = config.TEMPORAL_OUT / "temporal_aggregate.csv"
    if not agg_csv.exists():
        print("  ⚠ temporal_aggregate.csv not found – skipping fig5")
        return

    agg = pd.read_csv(agg_csv)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 5.5))

    # --- Left: Stacked area ---
    t = agg["t_mid_s"].values
    prog = agg["pct_Progressive_mean"].values
    np_m = agg["pct_Non-progressive_mean"].values
    imm = agg["pct_Immotile_mean"].values

    ax1.fill_between(t, 0, prog, color=CLASS_COLORS["Progressive"],
                     alpha=0.85, label="Progressive")
    ax1.fill_between(t, prog, prog + np_m,
                     color=CLASS_COLORS["Non-progressive"],
                     alpha=0.85, label="Non-progressive")
    ax1.fill_between(t, prog + np_m, prog + np_m + imm,
                     color=CLASS_COLORS["Immotile"],
                     alpha=0.85, label="Immotile")

    ax1.set_xlim(t.min(), t.max())
    ax1.set_ylim(0, 100)
    ax1.set_xlabel("Time (seconds)", fontweight="bold")
    ax1.set_ylabel("Proportion (%)", fontweight="bold")
    ax1.set_title("(a) Temporal Motility Distribution", fontweight="bold")
    ax1.legend(loc="upper right", framealpha=0.9, edgecolor="#cccccc")

    # --- Right: Line + CI bands ---
    for state, col_mean, col_std in [
        ("Progressive", "pct_Progressive_mean", "pct_Progressive_std"),
        ("Non-progressive", "pct_Non-progressive_mean", "pct_Non-progressive_std"),
        ("Immotile", "pct_Immotile_mean", "pct_Immotile_std"),
    ]:
        mean = agg[col_mean].values
        std = agg[col_std].values
        color = CLASS_COLORS[state]
        ax2.plot(t, mean, "-o", color=color, lw=2.5, markersize=6,
                 label=state, zorder=3)
        ax2.fill_between(t, mean - std, mean + std, color=color, alpha=0.15,
                         zorder=1)

    ax2.set_xlim(t.min(), t.max())
    ax2.set_ylim(0, 100)
    ax2.set_xlabel("Time (seconds)", fontweight="bold")
    ax2.set_ylabel("Mean Proportion ± 1 SD (%)", fontweight="bold")
    ax2.set_title("(b) Temporal Trends with Variability", fontweight="bold")
    ax2.legend(loc="upper right", framealpha=0.9, edgecolor="#cccccc")

    fig.suptitle("Motility Dynamics Over 30-Second Recording Window (n = 20 videos)",
                 fontweight="bold", fontsize=15, y=1.03)
    fig.tight_layout()
    _save(fig, out_dir / "fig5_temporal_dynamics.png")


