# Figure 7 – Multi-Model Ablation Comparison
# ═══════════════════════════════════════════════════════════════════════════

def fig7_model_comparison(out_dir: Path):
    """Grouped bar chart comparing MAE across detector × tracker combos."""
    metrics_json = (config.OUTPUTS_DIR / "evaluation_ablation"
                    / "multi_model_metrics.json")
    if not metrics_json.exists():
        print("  ⚠ multi_model_metrics.json not found – skipping fig7")
        return

    with open(metrics_json) as f:
        all_metrics = json.load(f)

    # Select most interesting experiments (prioritise bytetrack variants)
    preferred = [
        "yolov8n_bytetrack", "yolov8l_bytetrack",
        "yolov9t_bytetrack", "yolo11n_bytetrack",
        "rtdetr-l_bytetrack",
        "yolov8n_botsort", "yolov8l_botsort",
    ]
    experiments = [e for e in preferred if e in all_metrics]
    if not experiments:
        experiments = list(all_metrics.keys())[:8]

    categories = ["progressive", "non_progressive", "immotile"]
    cat_labels = ["Progressive", "Non-progressive", "Immotile"]

    n_exp = len(experiments)
    n_cat = len(categories)
    x = np.arange(n_cat)
    width = 0.8 / n_exp

    fig, ax = plt.subplots(figsize=(14, 6))

    for i, exp in enumerate(experiments):
        mae_vals = [all_metrics[exp].get(cat, {}).get("MAE", 0)
                    for cat in categories]
        offset = (i - n_exp / 2 + 0.5) * width
        bars = ax.bar(x + offset, mae_vals, width * 0.9,
                      color=DETECTOR_COLORS[i % len(DETECTOR_COLORS)],
                      edgecolor="white", linewidth=0.5,
                      label=exp.replace("_", " + ").title(), alpha=0.88)
        # Value labels on top
        for bar, val in zip(bars, mae_vals):
            if val > 0:
                ax.text(bar.get_x() + bar.get_width() / 2,
                        bar.get_height() + 0.4,
                        f"{val:.1f}", ha="center", va="bottom",
                        fontsize=7, fontweight="bold")

    ax.set_xticks(x)
    ax.set_xticklabels(cat_labels, fontweight="bold")
    ax.set_ylabel("Mean Absolute Error (%)", fontweight="bold")
    ax.set_title("Detector × Tracker Ablation — MAE vs Clinical Ground Truth",
                 fontweight="bold", pad=12)
    ax.legend(bbox_to_anchor=(1.02, 1), loc="upper left", fontsize=9,
              framealpha=0.9, edgecolor="#cccccc")
    ax.set_ylim(0)

    fig.tight_layout()
    _save(fig, out_dir / "fig7_model_comparison.png")


