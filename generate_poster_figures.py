def _apply_poster_style():
    """Set global matplotlib parameters for poster aesthetics."""
    plt.rcParams.update({
        "font.family": FONT_FAMILY,
        "font.size": 13,
        "axes.titlesize": 16,
        "axes.labelsize": 14,
        "xtick.labelsize": 11,
        "ytick.labelsize": 11,
        "legend.fontsize": 11,
        "figure.facecolor": BG_COLOR,
        "axes.facecolor": "#ffffff",
        "axes.edgecolor": "#cccccc",
        "axes.grid": True,
        "grid.color": GRID_COLOR,
        "grid.alpha": 0.5,
        "grid.linewidth": 0.5,
    })


def _save(fig, path: Path, tight: bool = True):
    """Save figure with consistent settings."""
    if tight:
        fig.savefig(path, dpi=POSTER_DPI, bbox_inches="tight",
                    facecolor=fig.get_facecolor(), pad_inches=0.3)
    else:
        fig.savefig(path, dpi=POSTER_DPI, facecolor=fig.get_facecolor())
    plt.close(fig)
    print(f"  ✓ Saved {path.name}")


def _load_all_motility() -> pd.DataFrame:
    """Load motility CSVs from all 20 videos."""
    frames = []
    for csv_path in sorted(config.EVENTS_OUT.glob("*_motility.csv")):
        df = pd.read_csv(csv_path)
        vid = csv_path.stem.replace("_motility", "")
        df["video"] = vid
        frames.append(df)
    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def _load_all_summaries() -> pd.DataFrame:
    """Load summary JSONs from all 20 videos."""
    rows = []
    for json_path in sorted(config.EVENTS_OUT.glob("*_summary.json")):
        with open(json_path) as f:
            rows.append(json.load(f))
    if not rows:
        return pd.DataFrame()
    return pd.DataFrame(rows)


