# Figure 2 – Cohort Motility Stacked Bar Chart
# ═══════════════════════════════════════════════════════════════════════════

def fig2_cohort_motility(out_dir: Path):
    """Stacked horizontal bar chart showing motility distribution per video."""
    summaries = _load_all_summaries()
    if summaries.empty:
        print("  ⚠ No summary data found – skipping fig2")
        return

    summaries = summaries.sort_values("video", key=lambda s: s.astype(int))

    videos = summaries["video"].astype(str).tolist()
    prog = summaries["progressive_pct"].values
    np_vals = summaries["non_progressive_pct"].values
    imm = summaries["immotile_pct"].values

    fig, ax = plt.subplots(figsize=(10, 7))

    y = np.arange(len(videos))
    bar_h = 0.65

    ax.barh(y, prog, height=bar_h, color=CLASS_COLORS["Progressive"],
            label="Progressive", edgecolor="white", linewidth=0.5)
    ax.barh(y, np_vals, height=bar_h, left=prog,
            color=CLASS_COLORS["Non-progressive"],
            label="Non-progressive", edgecolor="white", linewidth=0.5)
    ax.barh(y, imm, height=bar_h, left=prog + np_vals,
            color=CLASS_COLORS["Immotile"],
            label="Immotile", edgecolor="white", linewidth=0.5)

    # WHO reference lines
    ax.axvline(42, color="#555555", ls="--", lw=1.2, alpha=0.7)
    ax.text(42.5, len(videos) - 0.3, "WHO total\nmotility ≥ 42 %",
            fontsize=8, color="#555555", va="top")
    ax.axvline(30, color="#888888", ls=":", lw=1.0, alpha=0.6)
    ax.text(30.5, len(videos) - 0.3, "WHO prog.\n≥ 30 %",
            fontsize=8, color="#888888", va="top")

    ax.set_yticks(y)
    ax.set_yticklabels([f"Video {v}" for v in videos])
    ax.set_xlabel("Percentage (%)", fontweight="bold")
    ax.set_xlim(0, 100)
    ax.invert_yaxis()
    ax.legend(loc="lower right", framealpha=0.9, edgecolor="#cccccc")
    ax.set_title("Motility Distribution Across 20 VISEM Videos",
                 fontweight="bold", pad=12)

    # Track count annotations
    for i, (v, t) in enumerate(
            zip(videos, summaries["total_tracks"].values)):
        ax.text(101, i, f"n={int(t)}", va="center", fontsize=8,
                color="#666666")

    _save(fig, out_dir / "fig2_cohort_motility_bars.png")


