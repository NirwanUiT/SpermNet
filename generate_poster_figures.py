# Figure 4 – Predicted vs Ground Truth Correlation
# ═══════════════════════════════════════════════════════════════════════════

def fig4_gt_correlation(out_dir: Path):
    """Three-panel scatter plot of predicted vs clinical ground truth."""
    gt_csv = config.OUTPUTS_DIR / "evaluation" / "gt_comparison.csv"
    if not gt_csv.exists():
        print("  ⚠ gt_comparison.csv not found – skipping fig4")
        return

    merged = pd.read_csv(gt_csv)

    categories = [
        ("gt_progressive", "pred_progressive", "Progressive", CLASS_COLORS["Progressive"]),
        ("gt_non_progressive", "pred_non_progressive", "Non-progressive", CLASS_COLORS["Non-progressive"]),
        ("gt_immotile", "pred_immotile", "Immotile", CLASS_COLORS["Immotile"]),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(16, 5.5))

    for ax, (gt_col, pr_col, title, color) in zip(axes, categories):
        gt = merged[gt_col].values
        pr = merged[pr_col].values

        # Identity line
        lim = max(gt.max(), pr.max()) + 5
        ax.plot([0, lim], [0, lim], "--", color="#aaaaaa", lw=1.2,
                label="Perfect agreement", zorder=1)

        # Scatter
        ax.scatter(gt, pr, s=70, c=color, edgecolors="white", linewidth=0.8,
                   alpha=0.85, zorder=3)

        # Regression line
        if len(gt) > 2:
            slope, intercept, r_val, p_val, _ = stats.linregress(gt, pr)
            x_fit = np.linspace(0, lim, 100)
            ax.plot(x_fit, slope * x_fit + intercept, "-", color=color,
                    lw=2, alpha=0.7, zorder=2)
            # Annotation box
            txt = f"r = {r_val:.3f}\np = {p_val:.4f}"
            ax.text(0.05, 0.95, txt, transform=ax.transAxes, fontsize=10,
                    va="top", ha="left",
                    bbox=dict(boxstyle="round,pad=0.4", facecolor="white",
                              edgecolor=color, alpha=0.85))

        # Video labels
        if "video" in merged.columns:
            for _, row in merged.iterrows():
                ax.annotate(str(int(row["video"])),
                            (row[gt_col], row[pr_col]),
                            fontsize=7, alpha=0.55, ha="center",
                            va="bottom", xytext=(0, 4),
                            textcoords="offset points")

        ax.set_xlim(0, lim)
        ax.set_ylim(0, lim)
        ax.set_aspect("equal")
        ax.set_xlabel("Clinical Ground Truth (%)", fontweight="bold")
        ax.set_ylabel("SpermNet Predicted (%)", fontweight="bold")
        ax.set_title(title, fontweight="bold", color=color, fontsize=14)
        ax.legend(loc="lower right", fontsize=9, framealpha=0.8)

    fig.suptitle("Pipeline Predictions vs Clinical Semen Analysis (n = 20 videos)",
                 fontweight="bold", fontsize=15, y=1.03)
    fig.tight_layout()
    _save(fig, out_dir / "fig4_gt_correlation.png")


