# Figure 3 – WHO Kinematic Violin Plots
# ═══════════════════════════════════════════════════════════════════════════

def fig3_kinematic_violins(out_dir: Path):
    """Violin + strip plots of kinematic parameters by motility class."""
    all_mot = _load_all_motility()
    if all_mot.empty:
        print("  ⚠ No motility data found – skipping fig3")
        return

    # Standardise motility labels
    label_map = {
        "progressive": "Progressive",
        "non_progressive": "Non-progressive",
        "immotile": "Immotile",
    }
    all_mot["Motility"] = all_mot["motility"].map(label_map)
    all_mot = all_mot.dropna(subset=["Motility"])

    metrics = [
        ("VCL", "VCL (µm/s)\nCurvilinear Velocity"),
        ("VSL", "VSL (µm/s)\nStraight-line Velocity"),
        ("VAP", "VAP (µm/s)\nAverage-path Velocity"),
        ("LIN", "LIN (ratio)\nLinearity"),
        ("STR", "STR (ratio)\nStraightness"),
    ]

    fig, axes = plt.subplots(1, 5, figsize=(20, 5.5))

    order = ["Progressive", "Non-progressive", "Immotile"]
    palette = [CLASS_COLORS[c] for c in order]

    for ax, (col, ylabel) in zip(axes, metrics):
        if col not in all_mot.columns:
            ax.set_visible(False)
            continue

        sns.violinplot(data=all_mot, x="Motility", y=col, hue="Motility",
                       order=order, hue_order=order,
                       palette=palette, inner=None, cut=0, ax=ax, alpha=0.35,
                       linewidth=0, legend=False)
        sns.stripplot(data=all_mot, x="Motility", y=col, hue="Motility",
                      order=order, hue_order=order,
                      palette=palette, size=2.5, alpha=0.5, jitter=0.25,
                      ax=ax, linewidth=0, legend=False)
        sns.boxplot(data=all_mot, x="Motility", y=col, hue="Motility",
                    order=order, hue_order=order,
                    palette=palette, width=0.15, fliersize=0, ax=ax,
                    linewidth=1.2, boxprops=dict(alpha=0.7), legend=False)

        ax.set_xlabel("")
        ax.set_ylabel(ylabel, fontsize=10)
        ax.tick_params(axis="x", rotation=25)

    fig.suptitle("WHO Kinematic Parameters by Motility Class (n = {:,} tracks)"
                 .format(len(all_mot)),
                 fontweight="bold", fontsize=15, y=1.02)
    fig.tight_layout()
    _save(fig, out_dir / "fig3_kinematic_violins.png")


